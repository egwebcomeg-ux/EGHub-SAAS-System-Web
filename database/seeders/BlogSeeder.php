## الخطوة التانية: متنساش الهالك

الخضار بيتقشّر وبيترمي منه جزء، واللحمة ليها دهون وأطراف بتتشال. لو بتشتري كيلو طماطم وبتستخدم منه فعلاً ٨٥٠ جرام بعد التنضيف، يبقى تمن الكيلو "الصافي" أعلى من تمن الكيلو اللي في الفاتورة.

**التمن الفعلي = تمن الكيلو ÷ نسبة الصافي**

مثال: كيلو بـ٢٠ جنيه وصافيه ٨٥٪ يبقى تمنه الحقيقي حوالي ٢٣.٥ جنيه. الخطوة دي لوحدها ممكن تغيّر تكلفة طبق كامل بكذا جنيه، وطريقة قياسها سهلة: وزّن الخامة قبل وبعد التنضيف كذا مرة وخد المتوسط.

