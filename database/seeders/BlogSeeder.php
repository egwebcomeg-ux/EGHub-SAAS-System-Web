طريقة بسيطة تعرفها بيها: اجمع كل مصاريفك غير الخامات في الشهر، واقسمها على المبيعات المتوقعة. لو طلعت إنها بتاكل ٥٠٪ من المبيعات، وإنت عايز ربح صافي ١٥٪، يبقى فاضل للخامات ٣٥٪ بالكتير.

## الخطوة الرابعة: احسب السعر

**السعر المقترح = التكلفة ÷ النسبة المستهدفة**

البرجر اللي تكلفته ٩١ جنيه، بنسبة مستهدفة ٣٢٪: ٩١ ÷ ٠.٣٢ = حوالي ٢٨٤ جنيه. قرّبه لرقم منطقي زي ٢٨٥.

بعد كده بُص على السوق. لو السعر ده أعلى بكتير من المنطقة، قدامك اختيارات أحسن من إنك تبيع بخسارة:

- قلّل تكلفة حاجة مش باينة للعميل، زي مورد تاني للعلب أو الأكياس.
- عدّل الحجم واكتبه صريح في المنيو، مش في السر.
- خلّيه صنف بيجيب الزبون بنسبة أعلى شوية، وعوّض في الأصناف اللي بتتطلب معاه زي البطاطس والمشروب.

