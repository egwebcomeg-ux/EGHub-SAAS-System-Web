## في السعر، ولا لوحدها

فيه تلات طرق، ولكل واحدة ميزة وعيب:

**١. تدخّلها في سعر الصنف.** العميل بيشوف سعر واحد ومفيش مفاجآت. دي الأوضح. العيب إن الصالة والتيك أواي ليهم نفس السعر، فلو التغليف عالي، يا الصالة بتدفع حاجة مش بتاخدها، يا التيك أواي بيكسبك أقل.

**٢. سعر مختلف للتيك أواي والدليفري.** أصناف الدليفري بسعر أعلى شوية من الصالة. منطقي لو فرق التغليف كبير، بشرط إن العميل يشوفه قبل ما يطلب.

**٣. رسوم تغليف على الفاتورة.** صريحة، بس عملاء كتير بيضايقوا من بند زيادة في الآخر. لو استعملتها، اكتبها في المنيو قبل الطلب، مش في الفاتورة بس.

