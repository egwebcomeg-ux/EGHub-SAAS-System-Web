## الطلب مش الصنف

غلطة شائعة: تحسب التغليف على الصنف، والعميل طالب ٣ أصناف في طلب واحد. الكيس والاستيكر والمناديل بيخرجوا مرة واحدة مع الطلب، والعلب بتتحسب لكل صنف. قسّمهم كده:

