// تقرير المدير اليومي: الإعداد في الإعدادات ← الرسايل، اللي فيه، والتقرير الأسبوعي، وإشعار الموبايل.
module.exports = {
    id: 'daily-digest', title: 'تقرير المدير اليومي', as: 'owner', start: 'app:/settings?tab=messages',
    async run(t) {
        await t.say('تقرير المدير اليومي: كل يوم الصبح المالك والمديرين بيوصلهم ملخص اللي حصل امبارح.', 3800);
        await t.scroll('#weekly-report', 160);
        await t.point('[data-daily-digest]', 'من الإعدادات ← الرسايل: «تقارير للمديرين». التقرير اليومي شغال من الأول.', 3600);
        await t.say('فيه المبيعات بطرق الدفع، وكل إلغاء ومرتجع بسببه ومين وافق عليه، والخصومات...', 4000);
        await t.say('...ودرج كل وردية قصاد المتوقع، والطلبات اللي فضلت مفتوحة، وزيارات الشركات المستنية، والخامات اللي قربت تخلص.', 4600);
        await t.say('بيوصل على الإيميل وإشعار على الموبايل، واليوم اللي مفيهوش طلبات مش بيتبعت.', 3600);
        await t.click('#weekly-report input[type=checkbox][name=weekly_report_email]', 'وكمان: أرقام الأسبوع على الإيميل كل يوم اتنين الساعة 8 الصبح.', 1600);
        await t.click((p) => p.getByRole('button', { name: 'حفظ الإعدادات' }), 'واحفظ.', 1800);
        await t.go('app:/notifications/push', 'وكل مدير يختار من «إشعارات الموبايل» إيه اللي يرن على موبايله.');
        await t.point((p) => p.locator('[data-push-form] label').filter({ hasText: 'تقرير المدير اليومي' }), 'ومنها «تقرير المدير اليومي».', 3600);
    },
};
