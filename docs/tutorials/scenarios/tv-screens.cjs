        'دوس «إضافة شاشة».': 'اضغط إضافة شاشة.',
        'كل شاشة ليها قايمة عرض: المنيو، صور، وفيديوهات.': 'كل شاشة ليها قايمة عرض فيها المنيو، والصور، والفيديوهات.',
